package one.lindegaard.CustomItemsLib.rewards;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.StandardCopyOption;
import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

import org.bukkit.Bukkit;
import org.bukkit.ChatColor;
import org.bukkit.Location;
import org.bukkit.Material;
import org.bukkit.block.Block;
import org.bukkit.configuration.ConfigurationSection;
import org.bukkit.configuration.InvalidConfigurationException;
import org.bukkit.configuration.file.YamlConfiguration;
import org.bukkit.metadata.FixedMetadataValue;
import org.bukkit.plugin.Plugin;

import one.lindegaard.CustomItemsLib.Core;
import one.lindegaard.CustomItemsLib.Tools;
import one.lindegaard.CustomItemsLib.materials.Materials;

public class RewardBlockManager {

	private final Plugin plugin;
	private final File file;
	private YamlConfiguration config = new YamlConfiguration();
	private boolean dataChanged = false;
	private long changeVersion = 0;

	private final Object rewardBlocksLock = new Object();
	private final Object saveLock = new Object();
	private final HashMap<Integer, RewardBlock> rewardBlocks = new HashMap<Integer, RewardBlock>();

	public RewardBlockManager(Plugin plugin) {
		this.plugin = plugin;
		file = new File(plugin.getDataFolder().getParent(), "CustomItemsLib/rewards.yml");
		load();
		Core.getLegacyDataMigrator().migrateRewardFiles(this::importLegacyRewards, this::saveMigratedRewards);
		Bukkit.getPluginManager().registerEvents(new CoreRewardListeners(plugin), plugin);
	}

	/**
	 * Remove the Reward block from the world and clean up in saved rewards.
	 * 
	 * @param block
	 */
	public void removeReward(Block block) {
		if (Reward.isReward(block)) {
			Reward reward = Reward.getReward(block);
			Core.getMessages().debug("Removing block from world (id=%s)", reward.getUniqueID());
			block.getDrops().clear();
			block.setType(Material.AIR);
			block.removeMetadata(Reward.MH_REWARD_DATA_NEW, plugin);
			synchronized (rewardBlocksLock) {
				rewardBlocks.remove(reward.getUniqueID());
				markDataChanged();
			}
		}
	}

	public void addReward(Block block, Reward reward) {
		block.setMetadata(Reward.MH_REWARD_DATA_NEW, new FixedMetadataValue(plugin, reward));
		synchronized (rewardBlocksLock) {
			rewardBlocks.put(reward.getUniqueID(), new RewardBlock(block.getLocation(), reward));
			markDataChanged();
		}
	}

	public int getNextID() {
		synchronized (rewardBlocksLock) {
			int max = 0;
			for (int n : rewardBlocks.keySet())
				max = Math.max(max, n);
			return max + 1;
		}
	}

	private boolean isGenerated(Location location) {
		return location != null
				&& location.getWorld().isChunkGenerated(location.getChunk().getX(), location.getChunk().getZ());
	}

	public void saveData() {
		synchronized (saveLock) {
			Map<Integer, RewardBlock> snapshot;
			long snapshotVersion;
			synchronized (rewardBlocksLock) {
				if (!dataChanged)
					return;
				snapshot = copyRewardBlocks();
				snapshotVersion = changeVersion;
			}

			YamlConfiguration savedConfig = new YamlConfiguration();
			savedConfig.options()
					.setHeader(Arrays.asList(new String[] { "This is the rewards placed as blocks.",
							"Do not edit this file manually!!!",
							"If you remove a section the reward will loose its value on next server restart." }));
			for (Map.Entry<Integer, RewardBlock> entry : snapshot.entrySet()) {
				Location location = entry.getValue().getLocation();
				Reward reward = entry.getValue().getReward();
				ConfigurationSection section = savedConfig.createSection(entry.getKey().toString());
				section.set("location", location);
				reward.save(section);
			}

			try {
				savedConfig.save(file);
				synchronized (rewardBlocksLock) {
					config = savedConfig;
					if (changeVersion == snapshotVersion)
						dataChanged = false;
				}
				Core.getMessages().debug("Saved %s rewards to disk", snapshot.size());
			} catch (IOException e) {
				e.printStackTrace();
			}
		}
	}

	private Map<Integer, RewardBlock> copyRewardBlocks() {
		Map<Integer, RewardBlock> snapshot = new HashMap<Integer, RewardBlock>();
		for (Map.Entry<Integer, RewardBlock> entry : rewardBlocks.entrySet()) {
			RewardBlock rewardBlock = entry.getValue();
			snapshot.put(entry.getKey(), new RewardBlock(rewardBlock.getLocation().clone(),
					new Reward(rewardBlock.getReward())));
		}
		return snapshot;
	}

	private void markDataChanged() {
		dataChanged = true;
		changeVersion++;
	}

	private boolean saveMigratedRewards() {
		saveData();
		synchronized (rewardBlocksLock) {
			return !dataChanged;
		}
	}

	private int importLegacyRewards(YamlConfiguration legacyRewards) throws InvalidConfigurationException {
		int imported = 0;
		for (String key : legacyRewards.getKeys(false)) {
			ConfigurationSection section = legacyRewards.getConfigurationSection(key);
			if (section == null)
				continue;

			Reward reward = new Reward();
			reward.read(section);
			Location location = (Location) section.get("location");
			if (location == null || location.getWorld() == null || !Materials.isSkull(location.getBlock().getType()))
				continue;

			synchronized (rewardBlocksLock) {
				boolean duplicate = false;
				for (RewardBlock existing : rewardBlocks.values()) {
					if (existing.getLocation().equals(location) && existing.getReward().equals(reward)) {
						duplicate = true;
						break;
					}
				}
				if (duplicate)
					continue;

				int id = getNextID();
				reward.setUniqueID(id);
				location.getBlock().setMetadata(Reward.MH_REWARD_DATA_NEW,
						new FixedMetadataValue(plugin, new Reward(reward)));
				rewardBlocks.put(id, new RewardBlock(location, reward));
				markDataChanged();
				imported++;
			}
		}
		return imported;
	}

	public void load() {
		int n = 0;
		int deleted = 0;
		try {
			if (file.exists())
				config.load(file);
		} catch (IllegalArgumentException | InvalidConfigurationException e) {
			Bukkit.getConsoleSender().sendMessage(Core.PREFIX + ChatColor.RED
					+ " The rewards.yml file contain broken rewards. They will be deleted. ");
		} catch (IOException e) {
			e.printStackTrace();
		}

		for (String key : config.getKeys(false)) {
			ConfigurationSection section = config.getConfigurationSection(key);
			Reward reward = new Reward();
			try {
				reward.read(section);
			} catch (InvalidConfigurationException e) {
				Bukkit.getConsoleSender()
						.sendMessage(Core.PREFIX + ChatColor.RED + " Could not load reward no. " + key + ".");
			}

			Location location = (Location) section.get("location");
			for (RewardBlock rb : rewardBlocks.values()) {
				if (rb.equals(new RewardBlock(location, reward)))
					continue;
			}
			if (isGenerated(location) && Materials.isSkull(location.getBlock().getType())) {
				n++;
				reward.setUniqueID(n);
				location.getBlock().setMetadata(Reward.MH_REWARD_DATA_NEW,
						new FixedMetadataValue(plugin, new Reward(reward)));
				rewardBlocks.put(n, new RewardBlock(location, reward));
				if (Tools.isUUID(key)) {
					deleted++;
					config.set(key, null);
				}
			} else {
				// This block is not a PLAYER_HEAD, delete the section.
				deleted++;
				config.set(key, null);
			}
		}

		try {

			if (deleted > 0) {
				Core.getMessages().debug("Deleted %s rewards from the rewards.yml file", deleted);
				File file_copy = new File(plugin.getDataFolder(), "rewards.yml.old");
				Files.copy(file.toPath(), file_copy.toPath(), StandardCopyOption.COPY_ATTRIBUTES,
						StandardCopyOption.REPLACE_EXISTING);
				config.save(file);
			}
			if (n > 0) {
				Core.getMessages().debug("Loaded %s rewards from the CustomItemsLib/rewards.yml file", n);
			}

		} catch (IOException e) {
			e.printStackTrace();
		}

	}

}
